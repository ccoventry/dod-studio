//! Directory scanning and duplicate auditing tool for GoldSrc/Source/Source2 demo files.

use clap::Parser;
use hl_demo_auditor::{collect_demos, find_duplicates, integrity_line, scan_dir};
use std::fs;
use std::path::PathBuf;

#[derive(Parser, Debug)]
#[command(
    version,
    about = "Audits folders for Half-Life engine family (.dem) files and reports duplicates."
)]
struct Args {
    /// Instead of looking for duplicates, check that every delta in each demo
    /// decodes against a frame the file has (#41): one line per demo, and a
    /// non-zero exit if any is broken or cannot be read.
    #[arg(long)]
    integrity: bool,

    /// Repair damaged demos (#15): cut out each hole, rebuild the joins, and
    /// write `<name>_repaired.dem` next to each demo. The original is never
    /// changed and no file is overwritten. Non-zero exit if any demo could not
    /// be repaired.
    #[arg(long, conflicts_with = "integrity")]
    repair: bool,

    /// Folders to scan for .dem files (with --integrity, demo files too)
    paths: Vec<PathBuf>,
}

fn main() {
    let args = Args::parse();
    if args.paths.is_empty() {
        eprintln!("Usage: hl-demo-auditor [--integrity | --repair] <folder-or-demo> ...");
        std::process::exit(1);
    }
    if args.integrity {
        std::process::exit(run_integrity(&args.paths));
    }
    if args.repair {
        std::process::exit(run_repair(&args.paths));
    }

    println!("Scanning directories...");
    let mut files = vec![];
    let cancel = std::sync::atomic::AtomicBool::new(false);
    for folder in &args.paths {
        if folder.exists() {
            scan_dir(folder, &mut files, &cancel, &None);
        } else {
            eprintln!("Warning: Path does not exist: {}", folder.display());
        }
    }

    println!(
        "Found {} total .dem files. Auditing for duplicates...",
        files.len()
    );

    let (unique_files, duplicate_groups, duplicate_count, space_wasted_bytes) =
        find_duplicates(files, &cancel, &None);

    println!(
        "Audit complete: {} unique files, {} duplicates found. Wasted space: {:.2} GB",
        unique_files.len(),
        duplicate_count,
        space_wasted_bytes as f64 / (1024.0 * 1024.0 * 1024.0)
    );

    // Generate duplicate report markdown
    let mut report_content = String::new();
    report_content.push_str("# Demo Audit & Deduplication Report\n\n");
    report_content.push_str("Generated by the `hl-demo-auditor` tool.\n\n");
    report_content.push_str("## Summary\n\n");
    let total_scanned = unique_files.len() + duplicate_count;
    report_content.push_str(&format!("* **Total Files Scanned**: {}\n", total_scanned));
    report_content.push_str(&format!("* **Unique Demos**: {}\n", unique_files.len()));
    report_content.push_str(&format!(
        "* **Duplicate Files Found**: {}\n",
        duplicate_count
    ));
    report_content.push_str(&format!(
        "* **Wasted Space**: {:.2} MB ({:.2} GB)\n\n",
        space_wasted_bytes as f64 / (1024.0 * 1024.0),
        space_wasted_bytes as f64 / (1024.0 * 1024.0 * 1024.0)
    ));

    report_content.push_str("## Duplicate Groups Found\n");
    report_content.push_str("All files under each group have identical content. You can safely delete the duplicate files listed under \"Duplicates\".\n\n");

    for (i, group) in duplicate_groups.iter().enumerate() {
        let size_mb = group.key.size as f64 / (1024.0 * 1024.0);
        let total_wasted_mb = size_mb * (group.files.len() - 1) as f64;
        report_content.push_str(&format!(
            "### Group {} (Size: {:.2} MB, Wasted: {:.2} MB, Hash: {:x})\n",
            i + 1,
            size_mb,
            total_wasted_mb,
            group.key.header_hash
        ));

        report_content.push_str("* **Identical Files**:\n");
        for file in &group.files {
            report_content.push_str(&format!("  - `{}`\n", file.display()));
        }
        report_content.push('\n');
    }

    if let Err(e) = fs::write("demo_deduplication_report.md", &report_content) {
        eprintln!("Error writing duplicates report: {}", e);
    } else {
        println!("Detailed duplicate report written to: demo_deduplication_report.md");
    }
}

/// `--integrity`: prints each demo's verdict as it is checked and returns the
/// exit code, 1 if any demo is broken or unreadable.
fn run_integrity(paths: &[PathBuf]) -> i32 {
    let (demos, missing) = collect_demos(paths);
    for path in &missing {
        eprintln!("No such file or folder: {}", path.display());
    }
    let mut bad = 0;
    for path in &demos {
        let (ok, line) = integrity_line(path);
        if !ok {
            bad += 1;
        }
        println!("{line}");
    }
    println!(
        "{} demos checked, {} OK, {bad} broken or unreadable",
        demos.len(),
        demos.len() - bad
    );
    if bad > 0 || !missing.is_empty() || demos.is_empty() {
        1
    } else {
        0
    }
}

/// `--repair`: repairs each demo named (each folder's demos too), printing what
/// it found as it goes, and returns the exit code, 1 if any could not be
/// repaired.
fn run_repair(paths: &[PathBuf]) -> i32 {
    use hl_demo_auditor::messages as text;
    use hl_demo_auditor::repair::{FileRepair, repair_file};
    let (demos, missing) = collect_demos(paths);
    for path in &missing {
        eprintln!("{}", text::no_such_path(&path.display().to_string()));
    }
    let (mut repaired, mut not_damaged, mut failed) = (0, 0, 0);
    for path in &demos {
        let name = path.display().to_string();
        let outcome = analysis::repair::no_hooks(|hooks| repair_file(path, hooks));
        match outcome {
            Ok(FileRepair::NotDamaged) => {
                not_damaged += 1;
                println!("{}", text::not_damaged(&name));
            }
            Ok(FileRepair::Repaired { path: out, report }) => {
                repaired += 1;
                println!("{}", text::repaired(&name, &out.display().to_string()));
                print_holes(&report);
                println!("{}", text::summary_line(&report));
            }
            Ok(FileRepair::Refused { report, reasons }) => {
                failed += 1;
                println!("{}", text::refused(&name));
                for reason in &reasons {
                    println!("  {}", text::refusal(reason));
                }
                print_holes(&report);
            }
            Err(e) => {
                failed += 1;
                println!("{e}");
            }
        }
    }
    println!(
        "{}",
        text::repair_totals(demos.len(), repaired, not_damaged, failed)
    );
    if failed > 0 || !missing.is_empty() || demos.is_empty() {
        1
    } else {
        0
    }
}

/// The holes a repair found, one line each.
fn print_holes(report: &analysis::repair::RepairReport) {
    use hl_demo_auditor::messages as text;
    for (n, hole) in report.holes.iter().enumerate() {
        println!("{}", text::hole_line(n + 1, hole));
    }
    if report.ends_at_last_hole {
        println!("{}", text::ends_at_break(report.holes.len()));
    }
}
